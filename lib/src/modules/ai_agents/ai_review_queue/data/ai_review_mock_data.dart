  static ReviewItem _item({
    required String id,
    required ReviewItemType type,
    required ReviewAgent agent,
    required String project,
    String? projectFull,
    required String title,
    required String shortTitle,
    required double amount,
    required DateTime requestedAt,
    required int slaHours,
    required String requester,
    ReviewStatus status = ReviewStatus.pending,
    required String titleLabel,
    String? title2,
    required String bodyLabel,
    required String body,
    required String backup,
    List<String> citations = const [],
    ReviewBasis? basisOverride,
  }) {
    final fields = <DraftField>[
      DraftField(
        id: 'title',
        label: titleLabel,
        value: title2 ?? title,
        required: true,
      ),
      DraftField(
        id: 'amount',
        label: 'Amount',
        value: AiqFormat.money(amount),
        kind: DraftFieldKind.amount,
      ),
      DraftField(
        id: 'body',
        label: bodyLabel,
        value: body,
        kind: DraftFieldKind.multiline,
        required: true,
      ),
      DraftField(
        id: 'backup',
        label: 'Backup',
        value: backup,
        kind: DraftFieldKind.readOnly,
      ),
    ];

    return ReviewItem(
      id: id,
      type: type,
      agent: agent,
      project: project,
      projectFull: projectFull,
      title: title,
      shortTitle: shortTitle,
      amountAtStake: amount,
      requestedAt: requestedAt,
      slaHours: slaHours,
      requester: requester,
      status: status,
      draftFields: fields,
      originalText: body,
      basis: basisOverride ??
          ReviewBasis(
            summary: backup,
            sourcesLine: 'daily logs (2), documents (2)',
            corpusCitations: citations.isEmpty ? const ['—'] : citations,
            modelLabel: 'claude (routed)',
            runId: 'run_${id.substring(3)}',
            auditLogRef: 'Audit Log G-09',
            inputUsed: '2 logs, 2 documents',
            inputSkipped: 'none',
            needsHumanVerification: type.humanGated,
          ),
    );
  }
